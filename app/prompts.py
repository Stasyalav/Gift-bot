PLAIN_JSON_INSTRUCTION = (
    "\n\nВерни только один JSON-объект без пояснений и без Markdown-разметки. "
    'Формат: {"gifts": [{"name": "...", "why": "...", "price_min": 1000, '
    '"price_max": 1500, "category": "..."}]}. '
    "В списке gifts должно быть ровно 5 элементов."
)


def build_user_prompt(
    brief: str,
    budget_rub: int,
    *,
    problems: list[str] | None = None,
    avoid_names: list[str] | None = None,
) -> str:
    """Собирает запрос пользователя для одной попытки генерации."""

    parts = [
        "Кому и какой повод:",
        brief.strip(),
        "",
        f"Бюджет: до {budget_rub} ₽.",
    ]

    if avoid_names:
        parts.extend(
            [
                "",
                "Не повторяй эти идеи из прошлой подборки:",
                ", ".join(f"«{name}»" for name in avoid_names) + ".",
            ]
        )

    if problems:
        parts.extend(
            [
                "",
                "Предыдущий ответ нарушил правила:",
                *[f"— {problem}" for problem in problems],
                "Сформируй новый ответ и исправь это.",
            ]
        )

    return "\n".join(parts)
